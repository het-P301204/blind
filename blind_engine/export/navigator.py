"""Export an ATT&CK Navigator layer from coverage results."""
from blind_engine.models import AttackDataset, CoverageResult


def _score_to_color(score: float) -> str:
    """Map a 0-100 coverage score to a Navigator heat-map hex colour."""
    if score <= 0:
        return "#ff6666"   # red   — no coverage
    if score < 25:
        return "#ff9933"   # orange — limited
    if score < 60:
        return "#ffff66"   # yellow — partial
    return "#66ff66"       # green  — strong


def export_navigator_layer(
    coverage: list[CoverageResult],
    dataset: AttackDataset,
    corpus_id: str,
) -> dict:
    """Return a Navigator 4.x layer dict (JSON-serialisable).

    The layer can be imported directly into https://mitre-attack.github.io/attack-navigator/.
    """
    techniques = []
    for cov in coverage:
        tactic = cov.tactics[0] if cov.tactics else ""
        techniques.append(
            {
                "techniqueID": cov.technique_id,
                "tactic": tactic,
                "score": round(cov.coverage_score, 1),
                "color": _score_to_color(cov.coverage_score),
                "comment": (
                    f"Rules: {cov.mapped_rule_count} | "
                    f"Level: {cov.coverage_level.value} | "
                    f"Score: {cov.coverage_score:.1f}"
                ),
                "enabled": True,
                "metadata": [
                    {"name": "corpus_id", "value": corpus_id},
                    {"name": "rule_count", "value": str(cov.mapped_rule_count)},
                    {"name": "coverage_level", "value": cov.coverage_level.value},
                    {"name": "telemetry_status", "value": cov.telemetry_status.value},
                    {"name": "validation_status", "value": cov.validation_status.value},
                ],
                "links": [],
                "showSubtechniques": False,
            }
        )

    return {
        "name": f"BLIND Coverage – {corpus_id}",
        "versions": {
            "attack": dataset.version,
            "navigator": "4.9",
            "layer": "4.5",
        },
        "domain": "enterprise-attack",
        "description": (
            f"Detection coverage layer generated by BLIND for corpus: {corpus_id}. "
            f"ATT&CK version: {dataset.version}."
        ),
        "filters": {
            "platforms": ["Windows", "Linux", "macOS", "Network", "Cloud"]
        },
        "sorting": 0,
        "layout": {
            "layout": "side",
            "aggregateFunction": "average",
            "showID": True,
            "showName": True,
            "showAggregateScores": True,
            "countUnscored": False,
            "expandedSubtechniques": "none",
        },
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {
            "colors": ["#ff6666", "#ffff66", "#66ff66"],
            "minValue": 0,
            "maxValue": 100,
        },
        "legendItems": [
            {"label": "No Coverage", "color": "#ff6666"},
            {"label": "Limited (<25)", "color": "#ff9933"},
            {"label": "Partial (<60)", "color": "#ffff66"},
            {"label": "Strong (≥60)", "color": "#66ff66"},
        ],
        "metadata": [
            {"name": "corpus_id", "value": corpus_id},
            {"name": "generated_by", "value": "BLIND v0.1.0"},
        ],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
    }
